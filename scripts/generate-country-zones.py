#!/usr/bin/env python3
"""Generate the country/time-zone seed migration from an IANA tzdata release (FR-CAT-14).

Usage:
    curl -O https://data.iana.org/time-zones/releases/tzdata<VERSION>.tar.gz
    tar xzf tzdata<VERSION>.tar.gz zone.tab version
    python3 scripts/generate-country-zones.py zone.tab version \
        > backend/services/booking-service/src/main/resources/db/migration/V3__seed_country_time_zones.sql

Uses zone.tab (one row per country and zone, every country listed) rather than zone1970.tab,
which shares one zone between several countries (e.g. Europe/Berlin for Norway).
Pick the release that matches the JDK's tzdb.dat so every zone is a valid java.time.ZoneId.
"""
import re
import sys

COUNTRY = re.compile(r"^[A-Z]{2}$")
ZONE = re.compile(r"^[A-Za-z0-9_+\-]+(/[A-Za-z0-9_+\-]+)*$")


def main(zone_tab_path, version_path):
    with open(version_path, encoding="utf-8") as f:
        version = f.read().strip()

    pairs = set()
    with open(zone_tab_path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            country, _coordinates, zone = line.rstrip("\n").split("\t")[:3]
            # Validate before writing values into SQL.
            if not COUNTRY.match(country) or not ZONE.match(zone):
                raise ValueError(f"unexpected row: {line!r}")
            pairs.add((country, zone))

    rows = sorted(pairs)
    print(f"-- Generated by scripts/generate-country-zones.py from IANA tzdata {version} zone.tab.")
    print(f"-- {len(rows)} country/zone pairs, {len({c for c, _ in rows})} countries. Do not edit by hand.")
    print("INSERT INTO country_time_zone (country_code, time_zone) VALUES")
    print(",\n".join(f"  ('{country}', '{zone}')" for country, zone in rows) + ";")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: generate-country-zones.py <zone.tab> <version>")
    main(sys.argv[1], sys.argv[2])
